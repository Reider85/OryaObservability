#!/bin/bash
# repmgr promote hook: promote node, repoint pgbouncer-warm, reload
set -euo pipefail

NODE_NAME=%n
PROMOTED_NODE_NAME=$NODE_NAME
PGBOUNCER_HOST=pgbouncer-warm
PGBOUNCER_PORT=6433
PGBOUNCER_USER=pgbouncer
PGBOUNCER_PASSWORD=pgbouncer
DYNAMIC_CONF_DIR=/var/lib/postgresql/pgbouncer-dynamic
DYNAMIC_CONF_FILE=${DYNAMIC_CONF_DIR}/dynamic.conf

# Promote the node (this is the hook command repmgrd runs)
echo "Promoting node $PROMOTED_NODE_NAME..."
repmgr standby promote --fast-checkpoint --copy-external-configuration-files

# Determine the promoted node's service name (should be %n)
echo "Promoted node: $PROMOTED_NODE_NAME"

# Determine remaining standby nodes (for warm_store_ro)
# repmgr cluster show returns a table; parse for nodes that are not primary and not this node
# Format: ID | Name | Role | Priority | Tags | Location | Priority | Paused
# Example: 2 | pg-replica-1 | standby | 100 | | default | 100 |
STANDBYS=$(repmgr cluster show --csv | awk -F, 'NR>1 && $3=="standby" && $2!="'$PROMOTED_NODE_NAME'" {print $2}')

# Update dynamic.conf
echo "Updating pgbouncer-warm dynamic configuration..."
mkdir -p "${DYNAMIC_CONF_DIR}"

# Generate new dynamic config
cat > "${DYNAMIC_CONF_DIR}/new-dynamic.conf" <<EOF
; generated by repmgr promote hook - do not edit
warm_store = host=${PROMOTED_NODE_NAME} port=5432 dbname=warm_store
EOF

# Add read-only entry if we have standbys
if [ -n "$STANDBYS" ]; then
    # Use first standby for read
    FIRST_STANDBY=$(echo "$STANDBYS" | head -n1)
    echo "warm_store_ro = host=${FIRST_STANDBY} port=5432 dbname=warm_store" >> "${DYNAMIC_CONF_DIR}/new-dynamic.conf"
else
    # No standbys available - point to primary for read too (degraded)
    echo "warm_store_ro = host=${PROMOTED_NODE_NAME} port=5432 dbname=warm_store" >> "${DYNAMIC_CONF_DIR}/new-dynamic.conf"
fi

# Atomic replace
mv "${DYNAMIC_CONF_DIR}/new-dynamic.conf" "${DYNAMIC_CONF_FILE}"

# Reload pgbouncer-warm
echo "Reloading pgbouncer-warm..."
if ! psql "host=${PGBOUNCER_HOST} port=${PGBOUNCER_PORT} dbname=pgbouncer user=${PGBOUNCER_USER} password=${PGBOUNCER_PASSWORD}" -c "RELOAD;" 2>/dev/null; then
    echo "WARNING: Failed to reload pgbouncer-warm via psql. Trying direct pgbouncer command..."
    # Fallback: try to find pgbouncer process and send signal
    if pgrep -f "pgbouncer.*pgbouncer-warm.ini"; then
        pkill -HUP -f "pgbouncer.*pgbouncer-warm.ini"
        echo "Sent HUP signal to pgbouncer-warm"
    else
        echo "ERROR: Could not find pgbouncer-warm process to reload"
    fi
fi

echo "Promote hook completed for $PROMOTED_NODE_NAME"