#!/bin/bash
# repmgr rejoin hook: after old primary rejoins cluster, update config if needed
set -euo pipefail

NODE_NAME=%n
NEW_PRIMARY_NAME=$(repmgr cluster show --csv | awk -F, 'NR>1 && $3=="primary" {print $2}")
PGBOUNCER_HOST=pgbouncer-warm
PGBOUNCER_PORT=6433
PGBOUNCER_USER=pgbouncer
PGBOUNCER_PASSWORD=pgbouncer
DYNAMIC_CONF_DIR=/var/lib/postgresql/pgbouncer-dynamic
DYNAMIC_CONF_FILE=${DYNAMIC_CONF_DIR}/dynamic.conf

# If this node is the primary, no need to update
if [ "$NODE_NAME" = "$NEW_PRIMARY_NAME" ]; then
    echo "Node $NODE_NAME is primary, no config update needed"
    exit 0
fi

# This node is a standby, ensure warm_store_ro points to a standby if available
echo "Node $NODE_NAME is standby, updating warm_store_ro to point to a standby"

# Determine other standby nodes (excluding this node and primary)
STANDBYS=$(repmgr cluster show --csv | awk -F, 'NR>1 && $3=="standby" && $2!="'$NODE_NAME'" {print $2}')

# Update dynamic.conf only if we have other standbys
if [ -n "$STANDBYS" ]; then
    echo "Updating pgbouncer-warm dynamic configuration..."
    mkdir -p "${DYNAMIC_CONF_DIR}"
    
    # Generate new dynamic config - warm_store points to primary, warm_store_ro to first standby
    cat > "${DYNAMIC_CONF_DIR}/new-dynamic.conf" <<EOF
; generated by repmgr rejoin hook - do not edit
warm_store = host=${NEW_PRIMARY_NAME} port=5432 dbname=warm_store
EOF
    
    FIRST_STANDBY=$(echo "$STANDBYS" | head -n1)
    echo "warm_store_ro = host=${FIRST_STANDBY} port=5432 dbname=warm_store" >> "${DYNAMIC_CONF_DIR}/new-dynamic.conf"
    
    # Atomic replace
    mv "${DYNAMIC_CONF_DIR}/new-dynamic.conf" "${DYNAMIC_CONF_FILE}"
    
    # Reload pgbouncer-warm
    echo "Reloading pgbouncer-warm..."
    if ! psql "host=${PGBOUNCER_HOST} port=${PGBOUNCER_PORT} dbname=pgbouncer user=${PGBOUNCER_USER} password=${PGBOUNCER_PASSWORD}" -c "RELOAD;" 2>/dev/null; then
        echo "WARNING: Failed to reload pgbouncer-warm via psql. Trying direct pgbouncer command..."
        if pgrep -f "pgbouncer.*pgbouncer-warm.ini"; then
            pkill -HUP -f "pgbouncer.*pgbouncer-warm.ini"
            echo "Sent HUP signal to pgbouncer-warm"
        else
            echo "ERROR: Could not find pgbouncer-warm process to reload"
        fi
    fi
else
    echo "No other standbys available, not updating warm_store_ro configuration"
fi

echo "Rejoin hook completed for $NODE_NAME"